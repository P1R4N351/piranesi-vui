#!/bin/bash
# Regular design-sync PULL — fire a headless claude agent to pull the Claude
# Design project into the canonical piranesi-vui repo per design-sync-pull.md.
# Durable: invoked from the system crontab. Idempotent + locked + logged.
# The PULL itself needs the DesignSync tool (claude.ai design login), so it runs
# inside a headless `claude -p` agent, not raw shell.
#
# THE SHELL OWNS THE ALERT (Piranesi-Main DECIDE: B, 2026-09-03; prime lane
# piranesi-main-120b-moe:latest, degraded=false, binding_eligible=true).
# The agent writes a machine-readable status file (.design-sync/last-run.json);
# this script reads it and issues exactly ONE deduped ntfy per tick.
#
# Why: DesignSync authorization on this host died at 2026-08-28T12:41 (it worked
# at 08:41 the same morning). In the 5.83 days to 2026-09-03T08:41 the cron had
# 35 scheduled ticks: 19 shed by cron-load-gate, 16 executed, 12 aborted on the
# missing auth, 4 died on Claude weekly quota, 0 succeeded. Each of those 12
# aborts paged Sat at priority HIGH describing one unchanging condition, with the
# wording regenerated by the LLM every run ("Aborted at step 1", "design-sync-pull
# aborted at step 1", "The DesignSync tool couldn't reach the design project").
# A recurring notice for a stable known condition trains the reader to ignore the
# channel. Dedupe in the shell is deterministic; dedupe in the prompt is a
# per-run hope — and the same prompt already produced a DS-source file count of
# 33/34/35 across runs whose repo never moved.
#
# P10 RELAXATIONS: Rule 10 `set -e` is deliberately OFF (as in the pre-2026-09-03
# script). The entire purpose of this file is to survive a non-zero agent exit,
# classify it, and still alert; `set -e` would abort before dispatch() ever ran and
# turn a quota exhaustion into silence. Everything else complies: no loops, no
# eval, no dynamic source, every function under 40 lines, and every external
# call's status checked or swallowed on the line that swallows it.
set -uo pipefail

# Every path is env-overridable so the fault-injection suite
# (scripts/design-sync-pull.test.sh) can exercise EVERY alert branch without
# touching the real repo, the real log, the real dedupe stamps or Sat's phone.
# Defaults are the production values; an unset environment behaves exactly as
# the pre-2026-09-03 script did.
REPO="${DS_REPO:-/home/s/piranesi-vui}"
LOG="${DS_LOG:-/home/s/Piranesi/logs/design-sync-pull.log}"
CLAUDE="${DS_CLAUDE:-/home/s/.nvm/versions/node/v24.15.0/bin/claude}"
LOCK="${DS_LOCK:-/tmp/design-sync-pull.lock}"
NOTIFY="${DS_NOTIFY_SH:-/home/s/Piranesi/astroclaw/workspace/skills/notify.sh}"
STATUS_REL=.design-sync/last-run.json
AGENT_TIMEOUT="${DS_AGENT_TIMEOUT:-1500}"
STATUS=""      # ok-noop | ok-changed | noauth | error | missing | unparseable | stale
DETAIL=""
HEAD_SHA=""
START_EPOCH=0

log() { printf '%s %s\n' "$(date -Is)" "$*" >>"$LOG"; }

# One ntfy, always non-fatal to the run. Prints the notify rc into the log so a
# swallowed alert is still visible in the audit trail (never silently `|| true`).
emit() { # <priority> <key> <sig> <repeat-after> <title> <message>
  local rc=0
  bash "$NOTIFY" "$6" --title "$5" --priority "$1" \
    --dedupe-key "$2" --dedupe-sig "$3" --repeat-after "$4" \
    --tags design-sync >>"$LOG" 2>&1 || rc=$?
  log "notify key=$2 sig=$3 rc=$rc"
  return 0
}

# Drop a stamp so the NEXT occurrence of that condition alerts immediately
# instead of being swallowed by the previous episode's window. notify.sh's own
# docs make this the caller's duty.
clear_key() { # <key>
  bash "$NOTIFY" --dedupe-clear "$1" >>"$LOG" 2>&1 \
    || log "dedupe-clear $1 failed (non-fatal)"
  return 0
}

# Reduce a free-text detail to a STABLE dedupe signature: a new error re-alerts,
# the same error does not. Bounded to 48 chars so a volatile tail cannot defeat it.
sig_of() { # <prefix> <detail>
  local s
  s="$(printf '%s' "${2:-}" | tr 'A-Z' 'a-z' | tr -c 'a-z0-9' '-' | cut -c1-48)"
  printf '%s:%s' "$1" "${s:-none}"
}

# Read the agent's status file. Sets STATUS/DETAIL/HEAD_SHA. A file older than
# this run is STALE (the agent died before writing) and must not be believed.
read_status() {
  local f="$REPO/$STATUS_REL" mtime="" parsed=""
  if [[ ! -f "$f" ]]; then STATUS=missing; DETAIL="no $STATUS_REL written"; return 0; fi
  mtime="$(stat -c %Y "$f" 2>/dev/null)" || mtime=0
  if [[ ! "$mtime" =~ ^[0-9]+$ ]] || (( mtime < START_EPOCH )); then
    STATUS=stale; DETAIL="$STATUS_REL not rewritten this run (mtime=$mtime start=$START_EPOCH)"
    return 0
  fi
  parsed="$(python3 "$REPO/scripts/design-sync-status.py" "$f" 2>/dev/null)" || parsed=""
  if [[ -z "$parsed" ]]; then
    STATUS=unparseable; DETAIL="$STATUS_REL is not valid status JSON"; return 0
  fi
  STATUS="${parsed%%$'\t'*}"
  DETAIL="${parsed#*$'\t'}"
  return 0
}

# Map one status to exactly one alert decision. Every branch either emits or
# clears; there is no path that silently does nothing.
dispatch() {
  case "$STATUS" in
    ok-noop)
      clear_key design-sync-auth; clear_key design-sync-error; clear_key design-sync-status
      emit min design-sync-heartbeat "noop-${HEAD_SHA}" 7d \
        "design-sync-pull: no changes" "design-sync-pull: clean no-op at ${HEAD_SHA}. ${DETAIL}" ;;
    ok-changed)
      clear_key design-sync-auth; clear_key design-sync-error; clear_key design-sync-status
      emit default design-sync-change "changed-${HEAD_SHA}" 0 \
        "design-sync-pull: pulled changes" "design-sync-pull: ${DETAIL} (HEAD ${HEAD_SHA})" ;;
    noauth)
      clear_key design-sync-error; clear_key design-sync-status
      emit default design-sync-auth no-design-auth 7d \
        "design-sync-pull: paused, needs /design-login" \
        "design-sync-pull is PAUSED: DesignSync has no design-system authorization on piranesi-main. REMEDY: run /design-login ONCE from an interactive Claude Code session on this host — headless runs then reuse it. Nothing is being committed or deployed; repo and downstream bundles stay consistent at ${HEAD_SHA}. Design changes made upstream since the outage are NOT being pulled." ;;
    error)
      clear_key design-sync-auth
      emit high design-sync-error "$(sig_of error "$DETAIL")" 1d \
        "design-sync-pull: FAILED" "design-sync-pull failed: ${DETAIL}" ;;
    quota)
      emit low design-sync-quota weekly-limit 1d \
        "design-sync-pull: quota exhausted" "design-sync-pull could not run: Claude weekly limit reached. ${DETAIL}" ;;
    *)
      emit high design-sync-status "$(sig_of nostatus "$STATUS")" 1d \
        "design-sync-pull: no verdict" \
        "design-sync-pull ran but produced no usable verdict (${STATUS}): ${DETAIL}. The run's own report is missing, so neither success nor failure can be claimed." ;;
  esac
  return 0
}

PROMPT="Read scripts/design-sync-pull.md in this repo and follow it EXACTLY. It pulls the Claude Design project 8af39666-f588-49a2-a32d-e8e57314f5e5 (via the DesignSync tool) DOWN into this canonical repo: reconcile only DS-source files (NEVER the repo-only adapters/, scripts/, orb-params.json, .design-sync/), regenerate derived artifacts (scripts/verify-all.sh MUST pass), commit+push to gitea+github with CPCS attribution, and deploy the web bundles to the kiosk + branch-0 hall. Be strictly idempotent — a clean no-op when nothing changed. Do NOT send any ntfy yourself: step 6 is now the shell's job and a second page is noise. Your ONLY report channel is .design-sync/last-run.json, which you MUST write exactly once before you finish, per step 6 of the runbook. If the design project is unreachable OR the DesignSync tool lacks design authorization in this headless context, write status \"noauth\" and exit WITHOUT committing (do not fabricate)."

main() {
  [[ -r "$NOTIFY" ]] || { echo "$(date -Is) notify.sh missing at $NOTIFY" >>"$LOG"; exit 3; }
  cd "$REPO" || { log "repo missing"; exit 1; }
  [[ -x "$CLAUDE" ]] || CLAUDE="$(command -v claude)" || { log "no claude CLI"; exit 1; }
  local out rc=0
  out="$(mktemp /tmp/design-sync-pull.out.XXXXXX)" || { log "mktemp failed"; exit 3; }
  START_EPOCH="$(date +%s)"
  log "=== design-sync-pull start ==="
  timeout "$AGENT_TIMEOUT" "$CLAUDE" -p "$PROMPT" --dangerously-skip-permissions \
    >"$out" 2>&1 || rc=$?
  cat "$out" >>"$LOG" || log "could not append agent output"
  HEAD_SHA="$(git -C "$REPO" rev-parse --short HEAD 2>/dev/null)" || HEAD_SHA=unknown
  read_status
  if (( rc != 0 )) && [[ "$STATUS" != ok-noop && "$STATUS" != ok-changed ]]; then
    if grep -qi 'weekly limit' "$out"; then
      STATUS=quota; DETAIL="agent rc=$rc"
    elif [[ "$STATUS" == missing || "$STATUS" == stale ]]; then
      STATUS=error; DETAIL="agent rc=$rc and no status file written"
    fi
  fi
  rm -f "$out" || log "could not remove $out"
  dispatch
  log "=== design-sync-pull done rc=$rc status=$STATUS ==="
  return "$rc"
}

mkdir -p "$(dirname "$LOG")" || { echo "cannot create log dir" >&2; exit 3; }
exec 9>>"$LOCK"
flock -n 9 || { echo "$(date -Is) already running — skip" >>"$LOG"; exit 0; }
main
exit $?
